#!/usr/bin/env python3
"""Build TEMP before/after gallery composites for VO Stage F (no Godot GPU needed)."""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reports" / "visual_gallery"
ASSETS = ROOT / "client" / "assets"

SCREENS = [
    ("splash", ASSETS / "branding" / "bg_splash.jpg", ASSETS / "branding" / "ui_logo_wordmark.jpg"),
    ("home", ASSETS / "branding" / "bg_home.jpg", ASSETS / "ui" / "home" / "home_hero_stage.jpg"),
    ("dialog", ASSETS / "branding" / "bg_dialog.jpg", ASSETS / "dialogs" / "dialog_portrait_H13.jpg"),
    ("gacha", ASSETS / "branding" / "bg_gacha.jpg", ASSETS / "branding" / "gacha_portal.jpg"),
    ("shop", ASSETS / "branding" / "bg_shop.jpg", ASSETS / "ui" / "shop" / "shop_banner_featured.jpg"),
    ("party", ASSETS / "branding" / "bg_party.jpg", ASSETS / "characters" / "H01" / "H01_portrait.jpg"),
]


def _fit(im: Image.Image, size: tuple[int, int]) -> Image.Image:
    return im.convert("RGB").resize(size, Image.Resampling.LANCZOS)


def _panel(title: str, bg: Path, fg: Path | None, w: int = 270, h: int = 480) -> Image.Image:
    canvas = Image.new("RGB", (w, h), (16, 28, 53))
    if bg.is_file():
        canvas.paste(_fit(Image.open(bg), (w, h)), (0, 0))
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, w, 48], fill=(16, 28, 53))
    draw.text((12, 14), title, fill=(232, 188, 104))
    if fg and fg.is_file():
        inset = _fit(Image.open(fg), (w - 40, int((h - 80) * 0.55)))
        x = (w - inset.size[0]) // 2
        y = 72
        canvas.paste(inset, (x, y))
    draw.rectangle([8, 8, w - 9, h - 9], outline=(232, 188, 104), width=2)
    draw.text((12, h - 28), "TEMP · VO Stage F", fill=(183, 192, 212))
    return canvas


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, bg, fg in SCREENS:
        # Honest "before": flat navy + muted label (pre-polish placeholder feel)
        before = Image.new("RGB", (270, 480), (20, 28, 40))
        d = ImageDraw.Draw(before)
        d.rectangle([8, 8, 261, 471], outline=(90, 100, 120), width=2)
        d.text((24, 220), f"{name}\n(pre-VO stub)", fill=(150, 160, 180))
        after = _panel(f"AFTER · {name}", bg, fg)
        pair = Image.new("RGB", (560, 480), (10, 14, 24))
        pair.paste(before, (0, 0))
        pair.paste(after, (290, 0))
        out = OUT / f"compare_{name}.png"
        pair.save(out, optimize=True)
        after_only = OUT / f"after_{name}.png"
        after.save(after_only, optimize=True)
        rows.append((name, out.name, after_only.name))
        print("OK", out.relative_to(ROOT))

    # Extra: H13–H36 bust strip sample
    strip = Image.new("RGB", (960, 160), (16, 28, 53))
    for idx, i in enumerate(range(13, 25)):
        p = ASSETS / "dialogs" / f"dialog_portrait_H{i}.jpg"
        if p.is_file():
            strip.paste(_fit(Image.open(p), (70, 70)), (10 + idx * 78, 45))
    ImageDraw.Draw(strip).text((12, 12), "TEMP dialog busts H13–H24 sample", fill=(232, 188, 104))
    strip_path = OUT / "after_dialog_busts_sample.png"
    strip.save(strip_path, optimize=True)
    print("OK", strip_path.relative_to(ROOT))

    manifest = OUT / "MANIFEST.md"
    lines = [
        "# Visual gallery — VO Stage F",
        "",
        "> Generated by `scripts/generate_visual_gallery.py` (headless-safe). Art is **TEMP**.",
        "",
        "| Screen | Compare | After |",
        "|---|---|---|",
    ]
    for name, cmp_name, after_name in rows:
        lines.append(f"| {name} | `{cmp_name}` | `{after_name}` |")
    lines.append("")
    lines.append(f"- Dialog busts sample: `{strip_path.name}`")
    lines.append("- Theme: `client/themes/bashlegends_theme.tres`")
    lines.append("- Dialog busts: `client/assets/dialogs/dialog_portrait_H13.jpg` … `H36.jpg`")
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("OK", manifest.relative_to(ROOT))
    print(f"visual_gallery_ok pairs={len(rows)}")


if __name__ == "__main__":
    main()
